export function normalizeTicketPdfLanguage(value: unknown): TicketPdfLanguage {
  return value === "en" || value === "ur" || value === "ar" ? value : "ar";
}

export function ticketPdfLocale(language: TicketPdfLanguage): string {
  return language === "en" ? "en-US" : language === "ur" ? "ur-PK" : "ar-SA";
}

export function ticketPdfDir(language: TicketPdfLanguage): "ltr" | "rtl" {
  return language === "en" ? "ltr" : "rtl";
}

export function ticketPdfText(language: TicketPdfLanguage, arabic: string, vars: Record<string, string | number> = {}): string {
  let text = language === "ar" ? arabic : COPY[arabic]?.[language] || arabic;
  for (const [key, value] of Object.entries(vars)) text = text.replaceAll(`{${key}}`, String(value));
  return text;
}
