function interpolate(template: string, vars: Vars = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`));
}

export function purchaseOpsText(language: SupportedLanguage, source: string, vars?: Vars): string {
  const template = language === "ar" ? source : M[source]?.[language] ?? source;
  return interpolate(template, vars);
}

export function activeUiLanguage(): SupportedLanguage {
  if (typeof document !== "undefined") {
    const lang = document.documentElement.lang;
    if (lang === "ar" || lang === "en" || lang === "ur") return lang;
  }
  if (typeof localStorage !== "undefined") {
    const lang = localStorage.getItem("cmms-language");
    if (lang === "ar" || lang === "en" || lang === "ur") return lang;
  }
  return "ar";
}

export function usePurchaseOpsText() {
  const { language, dir } = useLanguage();
  return {
    language,
    dir,
    p: (source: string, vars?: Vars) => purchaseOpsText(language, source, vars),
  };
}
