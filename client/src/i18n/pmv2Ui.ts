function applyVars(text: string, vars?: Vars) {
  if (!vars) return text;
  return Object.entries(vars).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, value == null ? "" : String(value)),
    text,
  );
}

export function pmv2Text(language: SupportedLanguage, source: string, vars?: Vars) {
  if (language === "ar") return applyVars(source, vars);
  const translated = M[source]?.[language];
  return applyVars(translated || source, vars);
}


export function localizePmv2ServerText(language: SupportedLanguage, value: unknown) {
  const text = value == null ? "" : String(value);
  if (!text || language === "ar") return text;
  const exact = pmv2Text(language, text);
  if (exact !== text) return exact;

  const patterns: Array<[RegExp, string, string]> = [
    [/^بدأ تنفيذ البند:\s*(.+)$/u, "Started item: {value}", "آئٹم شروع: {value}"],
    [/^استكمال العمل على البند:\s*(.+)$/u, "Resumed work on item: {value}", "آئٹم پر کام دوبارہ شروع: {value}"],
    [/^توقف البند لاحتياج مواد:\s*(.+)$/u, "Item paused for materials: {value}", "مواد کی ضرورت پر آئٹم رکا: {value}"],
    [/^توقف البند لاحتياج بلاغ:\s*(.+)$/u, "Item paused for a ticket: {value}", "ٹکٹ کی ضرورت پر آئٹم رکا: {value}"],
    [/^اكتمل البند بعد إغلاق البلاغ:\s*(.+)$/u, "Item completed after ticket closure: {value}", "ٹکٹ بند ہونے کے بعد آئٹم مکمل: {value}"],
    [/^اكتمل البند:\s*(.+)$/u, "Item completed: {value}", "آئٹم مکمل: {value}"],
    [/^المواد أصبحت جاهزة لاستكمال البند:\s*(.+)$/u, "Materials ready to resume item: {value}", "آئٹم دوبارہ شروع کرنے کے لیے مواد تیار: {value}"],
    [/^تم إنشاء طلب مواد للبند:\s*(.+)$/u, "Material request created for item: {value}", "آئٹم کے لیے مواد درخواست بن گئی: {value}"],
    [/^بدأت زيارة للمهمة$/u, "Task visit started", "ٹاسک وزٹ شروع ہوا"],
    [/^انتهت زيارة المهمة$/u, "Task visit ended", "ٹاسک وزٹ ختم ہوا"],
    [/^زيارة\s*#(.+)$/u, "Visit #{value}", "وزٹ #{value}"],
    [/^سند الصرف\s+(.+)$/u, "Issue voucher {value}", "اجراء واؤچر {value}"],
    [/^الكمية\s+(.+)$/u, "Quantity {value}", "مقدار {value}"],
    [/^طلب الشراء\s+(.+)$/u, "Purchase request {value}", "خریداری درخواست {value}"],
    [/^البلاغ\s+(.+)$/u, "Ticket {value}", "ٹکٹ {value}"],
  ];
  for (const [pattern, en, ur] of patterns) {
    const match = text.match(pattern);
    if (match) return (language === "ur" ? ur : en).replace("{value}", match[1] ?? "");
  }
  return text;
}

export function usePmv2Text() {
  const { language, dir, isRTL } = useLanguage();
  return {
    language,
    dir,
    isRTL,
    p: (source: string, vars?: Vars) => pmv2Text(language, source, vars),
  };
}
